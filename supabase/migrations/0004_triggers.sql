-- ============================================================
-- SmartBank — 0004_triggers.sql
-- On new auth.users row, create profile (role=customer) and savings
-- account (with a freshly minted account number from the sequence).
-- Matches plan.md §6 / §11.
-- Idempotent: safe to re-run.
-- ============================================================

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  -- Insert profile (defaults role=customer).
  insert into public.profiles (id, full_name, email, phone, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name', split_part(new.email, '@', 1)),
    new.email,
    coalesce(new.raw_user_meta_data->>'phone', null),
    'customer'
  )
  on conflict (id) do nothing;

  -- Insert savings account if not already created (account_number generated by DEFAULT).
  if not exists (select 1 from public.accounts where user_id = new.id) then
    insert into public.accounts (user_id, account_type, balance, status)
    values (new.id, 'savings', 0, 'active');
  end if;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

